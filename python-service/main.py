# GET /events: Server-Sent Events stream
# ---------------------------------------------------------------------------
@app.get("/events")
async def sse_events():
    """
    Browser connects here once.  When helix-auto-scribe is toggled in the
    LaunchDarkly dashboard the UI updates instantly, with no reload needed.
    """
    global _main_loop
    _main_loop = asyncio.get_running_loop()

    queue: asyncio.Queue = asyncio.Queue()
    _sse_queues.append(queue)

    async def generate() -> AsyncGenerator[str, None]:
        # Send every watched flag's current state so each part page is in sync on connect.
        for _fk, _value in list(_flag_state.items()):
            yield f"data: {json.dumps({'flag': _fk, 'value': _value})}\n\n"

        try:
            while True:
                try:
                    payload = await asyncio.wait_for(queue.get(), timeout=30)
                    yield f"data: {payload}\n\n"
                except asyncio.TimeoutError:
                    # Keepalive comment: prevents proxy/browser from closing the stream
                    yield ": keepalive\n\n"
        finally:
            _sse_queues.remove(queue)

    return StreamingResponse(
        generate(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


