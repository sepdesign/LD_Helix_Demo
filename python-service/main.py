# POST /parent-connect: Newborn guidance AI ("my baby at 2am")
#
# Patient-facing endpoint.  Uses the same helix-clinical-ai AI Config but
# with a "maternity-parent" department context, which routes to the warm,
# empathetic Parent Connect variation (Claude Sonnet).
#
# Two layers can disable the AI: the helix-parent-connect boolean flag (the
# feature gate) and the helix-clinical-ai AI Config's own enable toggle. If
# either is off, the parent is routed to the 24/7 nurse line.
# ---------------------------------------------------------------------------
@app.post("/parent-connect")
async def parent_connect(request: Request):
    """
    Body (JSON):
      message  : str, parent's description of their newborn's symptoms
      userId   : str, patient/parent identifier
    """
    body = await request.json()
    message = body.get("message", "")
    user_key = body.get("userId", "parent-default")

    context = (
        Context.builder(user_key)
        .set("department", "maternity-parent")
        .set("patient_type", "postpartum")
        .build()
    )

    # Feature gate (boolean flag). The Patient Experience team can flip
    # helix-parent-connect OFF in LaunchDarkly to instantly route every parent to
    # the 24/7 nurse line -- independently of the helix-clinical-ai AI Config that
    # controls the model and prompt. Default True so the feature works before the
    # flag exists; if LD is unreachable the AI Config call below also fails safe.
    if not ld.variation("helix-parent-connect", context, True):
        return {
            "response": (
                "Our AI care assistant is turned off right now. "
                "Please call our 24/7 nurse line at 1-800-HELIX-RN for immediate guidance."
            ),
            "escalate": False,
            "model_used": None,
        }

    ai_config, tracker = ai_client.config("helix-clinical-ai", context, AIConfig(enabled=False))

    if not ai_config.enabled:
        return {
            "response": (
                "Our AI care assistant is temporarily unavailable. "
                "Please call our 24/7 nurse line at 1-800-HELIX-RN for immediate guidance."
            ),
            "escalate": False,
            "model_used": None,
        }

    model_name = (ai_config.model.name if ai_config.model and ai_config.model.name
                  else "claude-sonnet-4-5-20251001")
    system_prompt = next(
        (m.content for m in (ai_config.messages or []) if m.role == "system"),
        ("You are HELIX-PARENT, a compassionate care assistant for new parents. "
         "Provide evidence-based guidance in plain, reassuring language. "
         "Always recommend calling 911 or going to the ED for emergencies. "
         "Never diagnose. Guide parents on when to seek care."),
    )

    try:
        response = anthropic_client.messages.create(
            model=model_name,
            max_tokens=1024,
            system=system_prompt,
            messages=[{"role": "user", "content": message}],
        )

        tracker.track_success()
        tracker.track_tokens(
            TokenUsage(
                total=response.usage.input_tokens + response.usage.output_tokens,
                input=response.usage.input_tokens,
                output=response.usage.output_tokens,
            )
        )

        content = response.content[0].text
        # Escalation heuristic: detect when the assistant is recommending urgent or
        # emergency care so the UI can surface a prominent "call 911 / go to the ER"
        # banner. We match common phrasings the model uses, plus a word-boundary check
        # for the "ER" abbreviation so we do not false-match substrings like "fever".
        content_lc = content.lower()
        _emergency_phrases = (
            "911", "9-1-1",
            "emergency room", "emergency department", "emergency care",
            "emergency services", "emergency medical", "medical emergency",
            "go to the ed", "ed immediately", "nearest ed",
            "call an ambulance", "call for an ambulance",
            "seek emergency", "seek immediate", "immediate medical attention",
            "nearest emergency",
        )
        escalate = (
            any(p in content_lc for p in _emergency_phrases)
            or re.search(r"\b(?:to the|go to the|nearest|visit the|head to the)\s+er\b", content_lc) is not None
            or re.search(r"\ber\b\s+(?:immediately|right away|right now|now)\b", content_lc) is not None
        )

        return {
            "response": content,
            "escalate": escalate,
            "model_used": model_name,
        }

    except Exception as exc:
        return {"error": str(exc), "escalate": False}


